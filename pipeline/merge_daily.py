#!/usr/bin/env python3
"""Fold the local loop's generated cards (content/cards/daily-*.json) into their domain files
and queue them in data/needs_review.json for the next Claude review. Idempotent."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
cards_dir = ROOT / "content" / "cards"
queue_path = ROOT / "data" / "needs_review.json"
queue = json.loads(queue_path.read_text()) if queue_path.exists() else {"cards": []}
moved = 0
for f in sorted(cards_dir.glob("daily-*.json")):
    for card in json.loads(f.read_text()):
        dom = cards_dir / f"{card['domain']}.json"
        arr = json.loads(dom.read_text())
        if card["id"] not in {c["id"] for c in arr}:
            arr.append(card)
            dom.write_text(json.dumps(arr, indent=2, ensure_ascii=False))
            queue["cards"].append(card["id"])
            moved += 1
    f.unlink()
queue["why"] = "generated by the local daily loop; bring to house standard"
queue_path.write_text(json.dumps(queue, indent=1))
print(f"merged {moved} daily cards; {len(queue['cards'])} waiting for review")
